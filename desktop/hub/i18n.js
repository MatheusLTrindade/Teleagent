/**
 * @param {string} template
 * @param {Record<string, string | number>} vars
 */
function formatMessage(template, vars) {
	return template.replace(/\{(\w+)\}/g, (_, key) =>
		vars[key] !== undefined ? String(vars[key]) : `{${key}}`,
	);
}

